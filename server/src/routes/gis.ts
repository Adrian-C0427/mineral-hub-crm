gisRouter.get(
  "/wells/:fid",
  asyncHandler(async (req, res) => {
    const fid = Number(req.params.fid);
    if (!Number.isInteger(fid)) return res.status(400).json({ error: "invalid fid" });
    const rows = await prisma.$queryRawUnsafe<Record<string, unknown>[]>(
      `SELECT fid, api8, api10 AS api, well_no AS "wellNo", well_id AS "wellId", symbol, type, status,
              county, district, lease_no AS "leaseNo", lease_name AS "leaseName",
              operator, operator_no AS "operatorNo", field_no AS "fieldNo", field_name AS field,
              oil_gas AS "oilGas", formations, spud_date AS "spudDate", plug_date AS "plugDate",
              cum_oil AS "cumOil", cum_gas AS "cumGas", last_prod AS "lastProd",
              replace(abstract, '?', '') AS abstract, survey, abstract_id AS "abstractId",
              ST_X(geom) AS lon, ST_Y(geom) AS lat
         FROM rrc.wells WHERE fid = $1`,
      fid,
    );
    if (!rows.length) return res.status(404).json({ error: "well not found" });
    const well = rows[0];
    const [permits, completions] = await Promise.all([
      prisma.$queryRawUnsafe<Record<string, unknown>[]>(
        `SELECT status_no AS "statusNo", permit_date AS "permitDate", operator, lease_name AS "leaseName", well_no AS "wellNo"
           FROM rrc.permits WHERE api8 = $1 ORDER BY permit_date DESC NULLS LAST LIMIT 12`,
        String(well.api8 ?? "")),
      prisma.$queryRawUnsafe<Record<string, unknown>[]>(
        `SELECT tracking_no AS "trackingNo", filing_type AS "filingType", status,
                filed_date AS "filedDate", completion_date AS "completionDate", field_name AS "fieldName"
           FROM rrc.completions WHERE api8 = $1 ORDER BY filed_date DESC NULLS LAST LIMIT 12`,
        String(well.api8 ?? "")),
    ]);
    res.json({ ...well, permits, completions });
  }),
);

// Bound the raw string so a pathological county list can't build a giant
// ANY($1::text[]) array; the names are sliced again below as defense in depth.
const optionsSchema = z.object({ counties: z.string().max(4000).optional() });

/**
 * Survey/abstract filter option lists, optionally scoped to counties
 * (comma-separated names). Replaces the client building these from
 * downloaded GeoJSON.
 */
gisRouter.get(
  "/options",
  asyncHandler(async (req, res) => {
    const { counties } = optionsSchema.parse(req.query);
    const names = (counties ?? "").split(",").map((s) => s.trim()).filter(Boolean).slice(0, 500);

    // No county selected — every query below degrades to a full scan with a
    // DISTINCT/array_agg over the whole table, and the map issues this on load.
    // That statewide answer is identical for every caller and changes only on
    // ingest, so serve it from the same precomputed index /suggest uses.
    if (!names.length) {
      const ref = await referenceIndex();
      res.json({
        surveys: ref.surveys,
        abstracts: ref.abstracts,
        wellTypes: ref.types,
        wellStatuses: ref.statuses,
        operators: ref.operators.map((o) => o.name).sort(),
        wellCount: ref.wellCount,
      });
      return;
    }

    // County-scoped: these ride the county btree, so they stay live queries.
    const scope = `county = ANY($1::text[]) AND`;
    const params = [names];
    const surveys = await prisma.$queryRawUnsafe<{ v: string }[]>(
      `SELECT DISTINCT survey AS v FROM gis.abstracts WHERE ${scope} survey IS NOT NULL ORDER BY v`,
      ...params,
    );
    const abstracts = await prisma.$queryRawUnsafe<{ v: string }[]>(
      `SELECT DISTINCT replace(abstract, '?', '') AS v FROM gis.abstracts WHERE ${scope} abstract IS NOT NULL ORDER BY v`,
      ...params,
    );
    // Well-derived filter option lists from rrc.wells, same county scoping.
    const wScope = `WHERE county = ANY($1::text[])`;
    const wellAgg = await prisma.$queryRawUnsafe<{ types: string[]; statuses: string[]; operators: string[]; n: number }[]>(
      `SELECT array_agg(DISTINCT type) FILTER (WHERE type IS NOT NULL) AS types,
              array_agg(DISTINCT status) FILTER (WHERE status IS NOT NULL) AS statuses,
              array_agg(DISTINCT operator) FILTER (WHERE operator IS NOT NULL) AS operators,
              count(*)::int AS n
         FROM rrc.wells ${wScope}`,
      ...params,
    );
    const w = wellAgg[0];
    res.json({
      surveys: surveys.map((r) => r.v),
      abstracts: abstracts.map((r) => r.v).sort((a, b) => a.localeCompare(b, undefined, { numeric: true })),
      wellTypes: (w?.types ?? []).sort(),
      wellStatuses: (w?.statuses ?? []).sort(),
      operators: (w?.operators ?? []).sort(),
      wellCount: w?.n ?? 0,
    });
  }),
);

/**
 * Bounding box of everything matching the current map filters — powers the
 * map's "zoom to filtered results" behavior. Filter values arrive as repeated
 * query params (?operators=A&operators=B) because operator names can contain
 * commas. Precedence: any well-level filter (type/status/operator) frames the
 * matching wells; otherwise abstract/survey filters frame matching abstracts;
 * otherwise the selected counties frame themselves.
 */
/**
 * Pure query planner for /extent (exported for tests): picks the table whose
 * extent best represents "the filtered results" and builds the parameterized
 * predicate list. Returns null when no filter is set.
 */
export function planExtentQuery(q: Record<string, unknown>): { sql: string; params: string[][] } | null {
  const list = (k: string): string[] =>
    (Array.isArray(q[k]) ? (q[k] as unknown[]) : q[k] == null ? [] : [q[k]])
      .map((s) => String(s).trim()).filter(Boolean).slice(0, 500);
  const states = list("states"), counties = list("counties"), surveys = list("surveys"), abstracts = list("abstracts");
  const wellTypes = list("wellTypes"), wellStatuses = list("wellStatuses"), operators = list("operators");

  const params: string[][] = [];
  const cond = (col: string, vals: string[]): string => { params.push(vals); return `${col} = ANY($${params.length}::text[])`; };

  if (wellTypes.length || wellStatuses.length || operators.length) {
    const conds: string[] = [];
    if (counties.length) conds.push(cond("county", counties));
    if (surveys.length) conds.push(cond("survey", surveys));
    if (abstracts.length) conds.push(cond("replace(abstract, '?', '')", abstracts));
    if (wellTypes.length) conds.push(cond("type", wellTypes));
    if (wellStatuses.length) conds.push(cond("status", wellStatuses));
    if (operators.length) conds.push(cond("operator", operators));
    return { sql: `SELECT ST_Extent(geom)::text AS ext FROM rrc.wells WHERE ${conds.join(" AND ")}`, params };
  }
  if (surveys.length || abstracts.length) {
    const conds: string[] = [];
    if (counties.length) conds.push(cond("county", counties));
    if (surveys.length) conds.push(cond("survey", surveys));
    if (abstracts.length) conds.push(cond("replace(abstract, '?', '')", abstracts));
    return { sql: `SELECT ST_Extent(geom)::text AS ext FROM gis.abstracts WHERE ${conds.join(" AND ")}`, params };
  }
  if (counties.length) {
    return { sql: `SELECT ST_Extent(geom)::text AS ext FROM gis.counties WHERE ${cond("name", counties)}`, params };
  }
  // State filter alone: frame the whole state. GIS coverage is Texas-only
  // today, so any selection including TX frames the full county extent and a
  // non-TX-only selection has nothing to frame.
  if (states.length) {
    if (!states.some((s) => s.toUpperCase() === "TX")) return null;
    return { sql: `SELECT ST_Extent(geom)::text AS ext FROM gis.counties`, params };
  }
  return null;
}

gisRouter.get(
  "/extent",
  asyncHandler(async (req, res) => {
    const plan = planExtentQuery(req.query as Record<string, unknown>);
    if (!plan) return res.json({ bbox: null });
    const rows = await prisma.$queryRawUnsafe<{ ext: string | null }[]>(plan.sql, ...plan.params);
    res.json({ bbox: parseExtent(rows[0]?.ext ?? null) });
  }),
);


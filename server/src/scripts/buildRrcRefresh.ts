/**
 * Build the bundled Texas RRC refresh from the raw RRC downloads.
 *
 *   npx tsx src/scripts/buildRrcRefresh.ts --data-dir ~/rrc-data/2026-10 \
 *     --as-of 2026-10-18 --dbf900-date 2026-10-17 --uic-date 2026-10-01 \
 *     [--pdq-tsv /path/to/county-lease.tsv]
 *
 * Reads (from --data-dir): well{fips}.zip + surv{fips}.zip per county,
 * OG_WELLBORE_EWA_Report_<date>.csv, daf802.txt.gz, uif700a.txt.gz,
 * dbf900.ebc.gz, PDQ_DSV.zip. Writes server/data/rrc/*.json.gz (loaded at
 * boot by services/rrcRefresh.ts), the reconciliation under
 * docs/reports/rrc-refresh-<as-of>/, and the refreshed status vocabulary into
 * the static heat-map well files (client/public/data/{county}-wells.geojson).
 *
 * Deterministic for the same inputs and --as-of (builtAt aside), so the
 * bundles' content hashes — their dataset versions — only change when RRC's
 * data or the rules do.
 */
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { buildRefresh, type RefreshReport } from "../ingest/refresh/build.js";
import { ABSTRACTS_DATASET, PRODUCTION_DATASET, WELLS_DATASET, type CountyScope, type WellRow } from "../ingest/refresh/dataset.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const COUNTIES: CountyScope[] = [
  { code: "073", name: "Cherokee" },
  { code: "161", name: "Freestone" },
  { code: "289", name: "Leon" },
];

function arg(name: string, fallback?: string): string {
  const i = process.argv.indexOf(`--${name}`);
  const v = i >= 0 ? process.argv[i + 1] : fallback;
  if (v == null) throw new Error(`missing --${name}`);
  return v;
}
const ymd = (iso: string) => {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(iso)) throw new Error(`expected YYYY-MM-DD, got ${iso}`);
  return iso.replace(/-/g, "");
};

const csv = (rows: Record<string, unknown>[]): string => {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const cell = (v: unknown) => {
    const s = v == null ? "" : String(v);
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return [cols.join(","), ...rows.map((r) => cols.map((c) => cell(r[c])).join(","))].join("\n") + "\n";
};

function writeGz(file: string, value: unknown): number {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const buf = zlib.gzipSync(Buffer.from(JSON.stringify(value)), { level: 9 });
  fs.writeFileSync(file, buf);
  return buf.length;
}

/** Status/type/profile of the static heat-map well files follow the refreshed records (other properties untouched). */
function refreshHeatFiles(wells: readonly WellRow[]): string[] {
  const byFid = new Map(wells.map((w) => [w.fid, w]));
  const touched: string[] = [];
  for (const c of COUNTIES) {
    const file = path.join(ROOT, "client/public/data", `${c.name.toLowerCase()}-wells.geojson`);
    if (!fs.existsSync(file)) continue;
    const fc = JSON.parse(fs.readFileSync(file, "utf8")) as { features: { properties: Record<string, unknown> }[] };
    for (const f of fc.features) {
      const w = byFid.get(Number(f.properties.fid));
      if (!w) continue;
      Object.assign(f.properties, { status: w.status, category: w.category, type: w.type, symbol: w.symbol, profile: w.profile });
    }
    fs.writeFileSync(file, JSON.stringify(fc));
    touched.push(path.relative(ROOT, file));
  }
  return touched;
}

function reportMarkdown(r: RefreshReport, asOf: string, sizes: Record<string, number>): string {
  const s = r.summary as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
  const table = (o: Record<string, number>) => Object.entries(o).map(([k, v]) => `| ${k} | ${v.toLocaleString("en-US")} |`).join("\n");
  const lines = [
    `# Texas RRC data refresh — ${asOf}`,
    "",
    `Scope: ${s.scope}. Generated by \`server/src/scripts/buildRrcRefresh.ts\`; loaded into the database on deploy by \`services/rrcRefresh.ts\`.`,
    "",
    "## Sources (all the newest RRC publishes)",
    "",
    "| Source | File | RRC snapshot |",
    "|---|---|---|",
    ...(s.sources as { name: string; file: string; asOf: string }[]).map((x) => `| ${x.name} | ${x.file} | ${x.asOf} |`),
    "",
    "## Reconciliation",
    "",
    "| Measure | Count |",
    "|---|---|",
    `| Surface wells reviewed | ${s.reviewed.surfaceWells} |`,
    `| Deviated wellbores (horizontal/directional) | ${s.reviewed.deviatedWellbores} |`,
    `| Wellbore Query records reviewed | ${s.reviewed.wellboreQueryRows} |`,
    `| Status matched the map | ${s.matched} |`,
    `| Status corrected | ${s.corrected} |`,
    `| Status added (horizontal/directional surface spots had none) | ${s.statusAddedForHorizontalSurfaceSpots} |`,
    `| Needs investigation | ${s.needsInvestigation} |`,
    `| Wells with no API number (map symbol only) | ${s.wellsWithoutApi} |`,
    `| NAD27/NAD83 coordinate mismatches > 50 ft | ${s.locationMismatches} |`,
    `| RRC wellbores with no map location (not drawn; never fabricated) | ${s.missing.wellboresWithoutMapLocation} |`,
    `| Live permits with no map location | ${s.missing.activePermitsWithoutMapLocation} |`,
    `| Duplicate Wellbore Query rows collapsed into wellbores | ${s.duplicatesResolved.wellboreQueryRowsCollapsedToWellbores} |`,
    `| Malformed Wellbore Query rows skipped (statewide) | ${s.duplicatesResolved.malformedWellboreQueryRows} |`,
    "",
    "Added / retired / unchanged counts against the live database are computed by the loader at deploy time and recorded in `rrc.refresh_log`.",
    "",
    "### Status after the refresh",
    "",
    "| Status | Wells |",
    "|---|---|",
    table(s.statuses),
    "",
    "### Status changes (before → after)",
    "",
    "| Change | Wells |",
    "|---|---|",
    table(s.transitions),
    "",
    "### Flags",
    "",
    "| Flag | Wells |",
    "|---|---|",
    table(s.flags),
    "",
    "### Wellbore geometry",
    "",
    "| Measure | Count |",
    "|---|---|",
    table(Object.fromEntries(Object.entries(s.geometry).filter(([, v]) => typeof v === "number")) as Record<string, number>),
    "",
    "Every wellbore path is the straight line from RRC's surface location to its bottom-hole location and is labelled approximate: RRC publishes directional surveys only as scanned images, so no true trajectory exists in its bulk data.",
    "",
    "### Abstracts (RRC survey layer)",
    "",
    "| County | Polygons | Abstracts | Split pieces merged | Unnumbered (\"?\") tracts | Same number, other survey | No abstract number | Numbered in a neighboring county |",
    "|---|---|---|---|---|---|---|---|",
    ...Object.entries(s.abstracts as Record<string, Record<string, number>>).map(([c, a]) => `| ${c} | ${a.polygons} | ${a.abstracts} | ${a.mergedPieces} | ${a.questionLabels} | ${a.splitBySurvey} | ${a.unnumbered} | ${a.otherCountyPolygons} |`),
    "",
    "### Datum fit (RRC's NAD27 → NAD83 conversion, from each county's wells)",
    "",
    "| County | Control points | Inliers | Residual p50 (ft) | Residual p90 (ft) |",
    "|---|---|---|---|---|",
    ...Object.entries(s.datumFit as Record<string, Record<string, number>>).map(([c, d]) => `| ${c} | ${d.controlPoints} | ${d.inliers} | ${d.residualFtP50} | ${d.residualFtP90} |`),
    "",
    "## Detail files",
    "",
    "- `corrections.csv`: every well whose status changed, with the before/after and the deciding source.",
    "- `needs-investigation.csv`: wells whose records conflict or leave the status open.",
    "- `missing-location.csv`: wellbores RRC lists that have no map location.",
    "",
    "## Bundle sizes",
    "",
    ...Object.entries(sizes).map(([f, b]) => `- ${f}: ${(b / 1024).toFixed(0)} KB`),
    "",
  ];
  return lines.join("\n");
}

async function main(): Promise<void> {
  const dataDir = arg("data-dir").replace(/^~(?=\/)/, process.env.HOME ?? "~");
  const asOfIso = arg("as-of");
  const ewa = fs.readdirSync(dataDir).filter((f) => /^OG_WELLBORE_EWA_Report_\d{4}-\d{2}-\d{2}\.csv$/.test(f)).sort().at(-1);
  if (!ewa) throw new Error("no OG_WELLBORE_EWA_Report_<date>.csv in the data dir");
  const pdqTsvIdx = process.argv.indexOf("--pdq-tsv");
  const result = await buildRefresh({
    dataDir, counties: COUNTIES, asOf: ymd(asOfIso),
    files: { ewa, permits: "daf802.txt.gz", uic: "uif700a.txt.gz", dbf900: "dbf900.ebc.gz", pdq: "PDQ_DSV.zip" },
    pdqTsv: pdqTsvIdx >= 0 ? process.argv[pdqTsvIdx + 1] : undefined,
    asOfDates: { dbf900: arg("dbf900-date"), uic: arg("uic-date") },
    log: (m) => console.log(`[build] ${m}`),
  });

  const out = path.join(ROOT, "server/data/rrc");
  const sizes: Record<string, number> = {
    [WELLS_DATASET.file]: writeGz(path.join(out, WELLS_DATASET.file), result.wells),
    [ABSTRACTS_DATASET.file]: writeGz(path.join(out, ABSTRACTS_DATASET.file), result.abstracts),
    [PRODUCTION_DATASET.file]: writeGz(path.join(out, PRODUCTION_DATASET.file), result.production),
  };
  const reportDir = path.join(ROOT, "docs/reports", `rrc-refresh-${asOfIso}`);
  fs.mkdirSync(reportDir, { recursive: true });
  fs.writeFileSync(path.join(reportDir, "README.md"), reportMarkdown(result.report, asOfIso, sizes));
  fs.writeFileSync(path.join(reportDir, "corrections.csv"), csv(result.report.corrections));
  fs.writeFileSync(path.join(reportDir, "needs-investigation.csv"), csv(result.report.investigate));
  fs.writeFileSync(path.join(reportDir, "missing-location.csv"), csv(result.report.missingLocation));
  const heat = refreshHeatFiles(result.wells.wells);
  console.log(JSON.stringify({ sizes, report: path.relative(ROOT, reportDir), heatFiles: heat, summary: { statuses: result.report.summary.statuses, matched: result.report.summary.matched, corrected: result.report.summary.corrected } }, null, 2));
}

main().catch((e) => { console.error(e); process.exit(1); });
